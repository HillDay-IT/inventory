/*
| htmlspecialchars() prevents submitted text from being interpreted
| as HTML or JavaScript when displayed on the page.
*/

function editValue($value)
{
    return htmlspecialchars(
        (string)$value,
        ENT_QUOTES,
        'UTF-8'
    );
}

