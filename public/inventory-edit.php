<?php

/*
|--------------------------------------------------------------------------
| INVENTORY EDIT APPLICATION
|--------------------------------------------------------------------------
|
| This file demonstrates how to retrieve an existing inventory item,
| display its information in a form, and update that information.
|
| Existing MySQL Record
|       ↓
| PHP Variables
|       ↓
| HTML Form
|       ↓
| $_POST
|       ↓
| Validation
|       ↓
| Prepared SQL UPDATE Statement
|       ↓
| MySQL Database
|
*/


// -------------------------------------------------------------------------
// 1. LOAD THE DATABASE CONNECTION AND START THE SESSION
// -------------------------------------------------------------------------

/*
| session_start() allows us to use session variables.
|
| We use a session variable to store a security token that verifies
| the form submission.
|
| db.php creates the $conn variable that connects PHP to MySQL.
*/

session_start();

require __DIR__ . '/../config/db.php';


// -------------------------------------------------------------------------
// 2. CREATE ARRAYS AND DEFAULT VARIABLES
// -------------------------------------------------------------------------

/*
| These arrays contain the choices that users are allowed to submit.
|
| The subcategory array connects each subcategory ID to its name.
| The ID is stored in MySQL, but the name is displayed in the dropdown.
*/

$categories = [
    "1" => "Camera",
    "2" => "AV",
    "3" => "IT"
];

$subcategories = [
    1 => "Accessories",
    2 => "Audio",
    3 => "Lenses",
    4 => "Lighting",
    5 => "Camera Bodies"
];

$allowedAbility = [
    "Working",
    "Not tested",
    "Not working",
    "Partially working"
];

$allowedCondition = [
    "Fair",
    "Poor",
    "Good",
    "New"
];


$isTaggable = [
    "Yes",
    "No"
];

$isLoose = [
    "Yes",
    "No"
];

$errors = [];


// These variables will hold the inventory record.
$inventoryItem = null;

$message = '';


// -------------------------------------------------------------------------
// 3. CREATE THE SECURITY TOKEN
// -------------------------------------------------------------------------

/*
| A CSRF token helps verify that the form submission came from
| the form generated by this application.
|
| random_bytes() creates random data.
| bin2hex() converts that data into a hexadecimal string.
*/

if (!isset($_SESSION['inventory_csrf_token'])) {

    $_SESSION['inventory_csrf_token'] = bin2hex(random_bytes(32));

}


// -------------------------------------------------------------------------
// 4. IDENTIFY THE INVENTORY ITEM
// -------------------------------------------------------------------------

/*
| When someone clicks Edit, the inventory ID is sent through the URL.
|
| Example:
| inventory-edit.php?id=5
|
| $_GET retrieves the ID from the URL.
|
| If the form has already been submitted, we use the ID stored
| in $_POST instead.
*/

$rowId = $_POST['row_id'] ?? $_GET['id'] ?? '';

$primaryKey = '';


// Find the primary key column in the inv table.

$keyResult = $conn->query("SHOW KEYS FROM inv WHERE Key_name = 'PRIMARY'");

if ($keyResult !== false && ($keyRow = $keyResult->fetch_assoc())) {

    $candidateKey = $keyRow['Column_name'] ?? '';

    if (preg_match('/^[A-Za-z0-9_]+$/', $candidateKey)) {
        $primaryKey = $candidateKey;
    }
}

if ($keyResult !== false) {
    $keyResult->free();
}


// -------------------------------------------------------------------------
// 5. LOAD THE EXISTING INVENTORY RECORD
// -------------------------------------------------------------------------

/*
| SELECT retrieves the existing inventory information from MySQL.
|
| The WHERE statement identifies which inventory item we want.
|
| LIMIT 1 makes sure we only retrieve one record.
*/

if ($primaryKey === '' || $rowId === '') {

    $errors[] = "The inventory item could not be identified.";

} else {

    $sql = "SELECT
                category_id,
                sub_id,
                inv_name,
                inv_ability,
                inv_quantity,
                inv_condition,
                inv_taggable,
                inv_notes,
                inv_loose,
                inv_image
            FROM inv
            WHERE `{$primaryKey}` = ?
            LIMIT 1";


    // Prepare the SQL statement.

    $statement = $conn->prepare($sql);


    if ($statement === false) {

        $errors[] = "The inventory item could not be loaded.";

    } else {

        // Connect the inventory ID to the ? placeholder.

        $statement->bind_param('s', $rowId);


        // Execute the SELECT statement.

        $statement->execute();


        // Retrieve the matching record.

        $result = $statement->get_result();

        $inventoryItem = $result->fetch_assoc();


        // Close the prepared statement.

        $statement->close();


        if ($inventoryItem === null) {

            $errors[] = "The inventory item was not found.";

        }

    }

}


// -------------------------------------------------------------------------
// 6. GET THE VALUES SUBMITTED BY THE FORM
// -------------------------------------------------------------------------

/*
| This section only runs when the user submits the edit form.
|
| $_POST retrieves the new information.
|
| We store each submitted value in a PHP variable so that
| it is easier to validate and update.
*/

if ($_SERVER['REQUEST_METHOD'] === 'POST' && $inventoryItem !== null) {

    $category_id = $_POST['category_id'] ?? '';

    $subcategory_id = $_POST['subcategory_id'] ?? '';

    $inventoryName = trim($_POST['inv_name'] ?? '');

    $inventoryStatus = $_POST['inv_ability'] ?? '';

    $inventoryQuantity = trim($_POST['inv_quantity'] ?? '');

    $inventoryCondition = $_POST['inv_condition'] ?? '';

    $inventoryTaggable = $_POST['inv_taggable'] ?? '';

    $inventoryLoose = $_POST['inv_loose'] ?? '';

    $inventoryNotes = trim($_POST['inv_notes'] ?? '');

    $inventoryImage = trim($_POST['inv_image'] ?? '');


    // Update the displayed values so the form keeps submitted information.

    $inventoryItem = [
        'category_id' => $category_id,
        'subcategory_name' => $subcategory_id,
        'inv_name' => $inventoryName,
        'inv_ability' => $inventoryStatus,
        'inv_quantity' => $inventoryQuantity,
        'inv_condition' => $inventoryCondition,
        'inv_taggable' => $inventoryTaggable,
        'inv_notes' => $inventoryNotes,
        'inv_loose' => $inventoryLoose,
        'inv_image' => $inventoryImage
    ];


    // ---------------------------------------------------------------------
    // 7. VALIDATE THE SECURITY TOKEN
    // ---------------------------------------------------------------------

    /*
    | hash_equals() compares the saved security token with the submitted
    | token.
    |
    | If they do not match, the update is rejected.
    */

    if (!hash_equals(
        $_SESSION['inventory_csrf_token'],
        $_POST['csrf_token'] ?? ''
    )) {

        $errors[] = "The update request could not be verified.";

    }


    // ---------------------------------------------------------------------
    // 8. VALIDATE THE FORM VALUES
    // ---------------------------------------------------------------------

    /*
    | Before updating MySQL, we check that the submitted information
    | contains valid values.
    */


    // Validate category.

    if (!array_key_exists($category_id, $categories)) {

        $errors[] = "Please choose a valid category.";

    }


    // Validate item name.

    if ($inventoryName === '') {

        $errors[] = "Inventory name is required.";

    }


    // Validate camera subcategory.

    if ($category_id === "1") {

        if (
            !ctype_digit($subcategory_id) ||
            !array_key_exists((int)$subcategory_id, $subcategories)
        ) {

            $errors[] = "Please choose a valid camera subcategory.";

        }

    }


    // Validate inventory status.

    if (!in_array($inventoryStatus, $allowedAbility, true)) {

        $errors[] = "Please choose a valid inventory status.";

    }


    // Validate quantity.

    if (
        !ctype_digit($inventoryQuantity)
    ) {

        $errors[] = "Quantity must be a whole number.";

    }


    // Validate condition.

    if (!in_array($inventoryCondition, $allowedCondition, true)) {

        $errors[] = "Please choose a condition.";

    }


    // Validate taggable.

    if (!in_array($inventoryTaggable, $isTaggable, true)) {

        $errors[] = "Please select Yes or No for taggable.";

    }


    // Validate loose.

    if (!in_array($inventoryLoose, $isLoose, true)) {

        $errors[] = "Please select Yes or No for loose.";

    }


    // Validate image URL.

    if (
        $inventoryImage !== '' &&
        (
            filter_var($inventoryImage, FILTER_VALIDATE_URL) === false ||
            !in_array(
                parse_url($inventoryImage, PHP_URL_SCHEME),
                ['http', 'https'],
                true
            )
        )
    ) {

        $errors[] = "Please enter a valid image URL.";

    }


    // ---------------------------------------------------------------------
    // 9. UPDATE THE INVENTORY RECORD
    // ---------------------------------------------------------------------

    /*
    | count($errors) checks whether the validation section found any errors.
    |
    | If there are no errors, we can prepare the UPDATE statement.
    |
    | An UPDATE statement changes an existing record.
    | It does NOT create a new inventory record.
    */

    if (count($errors) === 0) {


        // Convert Yes/No into the values stored by MySQL.

        $taggableValue = ($inventoryTaggable === "Yes") ? 1 : 0;

        $looseValue = ($inventoryLoose === "Yes") ? 1 : 0;


        // Convert category, subcategory, and quantity into integers.

        $categoryValue = (int)$category_id;

        $subcategoryValue = ($category_id === "1")
            ? (int)$subcategory_id
            : null;

        $quantityValue = (int)$inventoryQuantity;


        // Write the UPDATE SQL command.

        $sql = "UPDATE inv SET
                    category_id = ?,
                    sub_id = ?,
                    inv_name = ?,
                    inv_ability = ?,
                    inv_quantity = ?,
                    inv_condition = ?,
                    inv_taggable = ?,
                    inv_notes = ?,
                    inv_loose = ?,
                    inv_image = ?
                WHERE `{$primaryKey}` = ?
                LIMIT 1";


        // -----------------------------------------------------------------
        // 10. PREPARE THE SQL STATEMENT
        // -----------------------------------------------------------------

        /*
        | prepare() sends the SQL structure to MySQL.
        |
        | The ? symbols are placeholders.
        |
        | We will connect the PHP variables to those placeholders
        | using bind_param().
        */

        $statement = $conn->prepare($sql);


        if ($statement === false) {

            $errors[] = "The update statement could not be prepared.";

        } else {


            // -------------------------------------------------------------
            // 11. BIND PHP VARIABLES TO THE ? PLACEHOLDERS
            // -------------------------------------------------------------

            /*
            | bind_param() connects each PHP variable to its matching
            | placeholder.
            |
            | The order of the variables must match the order of the
            | question marks in the SQL command.
            |
            | i = integer
            | s = string
            | d = decimal
            */

            $statement->bind_param(
                'iissisisiss',
                $categoryValue,
                $subcategoryValue,
                $inventoryName,
                $inventoryStatus,
                $quantityValue,
                $inventoryCondition,
                $taggableValue,
                $inventoryNotes,
                $looseValue,
                $inventoryImage,
                $rowId
            );


            // -------------------------------------------------------------
            // 12. EXECUTE THE UPDATE STATEMENT
            // -------------------------------------------------------------

            /*
            | execute() tells MySQL to perform the UPDATE.
            |
            | If successful, we redirect the user back to the inventory
            | table.
            */

            if ($statement->execute()) {

                $statement->close();

                header('Location: inventory-table.php?updated=1');

                exit;

            } else {

                $errors[] = "Database error: " . $statement->error;

            }


            // Close the prepared statement.

            $statement->close();

        }

    }

}


// -------------------------------------------------------------------------
// 13. CREATE A FUNCTION TO DISPLAY SAFE HTML VALUES
